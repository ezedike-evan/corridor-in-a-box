// Renders corridors/README.md, the catalog of every corridor manifest.
//
// A pure function of the manifests: rows are ordered by id and nothing depends
// on today's date, so the committed file is reproducible byte-for-byte and
// tests/corridors.test.ts can fail CI when a manifest lands without it.
//
// Liveness is computed as of each proof's own completion time. That makes
// `proven` mean "carries a proof block" here; whether that proof is still
// fresh is a run-time question, answered by `corridor plan`.

import { readdirSync } from "node:fs";
import { join } from "node:path";
import { liveness, LIVENESS_LABEL, loadCorridor, type Corridor } from "@corridor/manifest";

export const CATALOG_PATH = "corridors/README.md";

const HEADER = [
  "# Corridors",
  "",
  "Generated by `pnpm corridors:catalog` — do not edit by hand.",
  "",
  "One row per manifest in this directory. `liveness` is what the manifest earns on its own",
  "evidence (see `packages/manifest/src/liveness.ts`); only `verified` and `proven` lanes are",
  "runnable.",
  "",
];

const COLUMNS = [
  "id",
  "route",
  "dest",
  "dest asset",
  "network",
  "liveness",
  "verified",
  "note",
];

const cell = (s: string | undefined) =>
  (s ?? "").replace(/\s+/g, " ").trim().replace(/\|/g, "\\|") || "—";

function row(c: Corridor): string {
  const asOf = c.proof ? new Date(c.proof.canary_completed_at) : new Date(0);
  const state = liveness(c, asOf).state;
  return (
    "| " +
    [
      `\`${c.id}\``,
      cell(c.fx.path.join(" → ")),
      cell(c.dest.name),
      cell(c.dest.asset),
      cell(c.settlement.network),
      cell(LIVENESS_LABEL[state]),
      cell(c.dest.endpoints.endpoints_verified_at),
      cell(c.status_note),
    ].join(" | ") +
    " |"
  );
}

export function renderCatalog(corridors: readonly Corridor[]): string {
  const sorted = [...corridors].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return [
    ...HEADER,
    `| ${COLUMNS.join(" | ")} |`,
    `| ${COLUMNS.map(() => "---").join(" | ")} |`,
    ...sorted.map(row),
    "",
  ].join("\n");
}

export function loadAllCorridors(repoRoot: string): Corridor[] {
  const dir = join(repoRoot, "corridors");
  return readdirSync(dir)
    .filter((f) => f.endsWith(".corridor.yaml"))
    .map((f) => {
      const result = loadCorridor(join(dir, f));
      if (!result.ok) throw new Error(`corridors/${f}: ${result.error.message}`);
      return result.value;
    });
}
